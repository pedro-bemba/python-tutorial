# Before working with Python variables, it's important to understand data types. A data type describes the kind of value a variable holds, for example, a number or a piece of text.

# Python is a dynamically typed language. This means you do not specify a variable's data type when you create it. Python determines the type from the value assigned to the variable.

name = 'PEDRO BEMBA' # Python knows it is a string
age = 21 # Python knows it is an integer

# A variable can later be assigned a value of a different type:
age = 'twenty-one' # Now Python knows it is a string

weight = 70.5 # Float: A number with a decimal point
am_i_happy = True # Boolean: A true or false type, written as True or False
